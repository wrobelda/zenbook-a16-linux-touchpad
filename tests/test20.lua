dofile(os.getenv("T").."/harness.lua")
local S = os.getenv("S")
H.load({S.."/20-thumb-zone.lua", S.."/30-rest-deadzone.lua", S.."/40-scroll-scale.lua"})
-- 1. thumb rests in the top strip: libinput sees nothing
H.send(cat({E("ABS_MT_SLOT",0),E("ABS_MT_TRACKING_ID",10),E("ABS_MT_POSITION_X",1000),E("ABS_MT_POSITION_Y",200)}, K(1)))
H.check("thumb hidden: libinput touches", H.count(), 0)
H.check("thumb hidden: finger-count keys", H.keycount(), 0)
-- index finger taps lower down (kernel uses slot 1, reports 2 fingers)
H.send(cat({E("ABS_MT_SLOT",1),E("ABS_MT_TRACKING_ID",11),E("ABS_MT_POSITION_X",2500),E("ABS_MT_POSITION_Y",2200)}, K(2)))
H.check("index visible: libinput touches", H.count(), 1)
H.check("index visible: finger-count keys", H.keycount(), 1)
H.check("index visible: position", H.li.touches[1] and H.li.touches[1].y, 2200)
-- thumb wiggles inside the strip (kernel omits SLOT for slot 0 after slot 1? no: must send SLOT 0)
H.send({E("ABS_MT_SLOT",0),E("ABS_MT_POSITION_X",1010)})
H.check("thumb wiggle stays hidden", H.count(), 1)
H.send(cat({E("ABS_MT_SLOT",1),E("ABS_MT_TRACKING_ID",-1)}, K(1)))
H.check("index lifted: libinput touches", H.count(), 0)
H.check("index lifted: finger-count keys", H.keycount(), 0)
-- 2. thumb escapes downward past the strip + 5 mm (y > 30*32 = 960)
H.send({E("ABS_MT_SLOT",0),E("ABS_MT_POSITION_Y",900)})
H.check("thumb inside escape margin still hidden", H.count(), 0)
H.send({E("ABS_MT_POSITION_Y",1000)})
H.check("thumb escaped: visible as new touch", H.li.touches[0] and H.li.touches[0].tid, 10)
H.check("escaped touch starts at current position", H.li.touches[0] and H.li.touches[0].y, 1000)
H.check("escaped touch: finger-count keys", H.keycount(), 1)
H.send(cat({E("ABS_MT_TRACKING_ID",-1)}, K(0)))
H.check("escaped touch lifted", H.count(), 0)
-- 3. right strip (x >= 4762-480 = 4282) hidden, left of it visible
H.send(cat({E("ABS_MT_SLOT",0),E("ABS_MT_TRACKING_ID",20),E("ABS_MT_POSITION_X",4500),E("ABS_MT_POSITION_Y",2000)}, K(1)))
H.check("right strip hidden", H.count(), 0)
H.send(cat({E("ABS_MT_SLOT",1),E("ABS_MT_TRACKING_ID",21),E("ABS_MT_POSITION_X",4250),E("ABS_MT_POSITION_Y",2000)}, K(2)))
H.check("just left of right strip visible", H.count(), 1)
H.send(cat({E("ABS_MT_TRACKING_ID",-1),E("ABS_MT_SLOT",0),E("ABS_MT_TRACKING_ID",-1)}, K(0)))
H.check("all lifted", H.count(), 0)
-- 4. corner: stays hidden until out of both strips
H.send(cat({E("ABS_MT_SLOT",0),E("ABS_MT_TRACKING_ID",30),E("ABS_MT_POSITION_X",4500),E("ABS_MT_POSITION_Y",200)}, K(1)))
H.send({E("ABS_MT_POSITION_Y",2000)})
H.check("corner: out of top, still in right strip", H.count(), 0)
H.send({E("ABS_MT_POSITION_X",4000)})
H.check("corner: out of both strips", H.count(), 1)
H.send(cat({E("ABS_MT_TRACKING_ID",-1)}, K(0)))
-- 5. two real fingers: both visible, two-finger keys, scroll scaled by plugin 40
H.send(cat({E("ABS_MT_SLOT",0),E("ABS_MT_TRACKING_ID",40),E("ABS_MT_POSITION_X",2000),E("ABS_MT_POSITION_Y",1500),
            E("ABS_MT_SLOT",1),E("ABS_MT_TRACKING_ID",41),E("ABS_MT_POSITION_X",2500),E("ABS_MT_POSITION_Y",1500)}, K(2)))
H.check("two fingers: libinput touches", H.count(), 2)
H.check("two fingers: finger-count keys", H.keycount(), 2)
H.send({E("ABS_MT_SLOT",0),E("ABS_MT_POSITION_Y",1600),E("ABS_MT_SLOT",1),E("ABS_MT_POSITION_Y",1600)}, 10000)
H.check("two-finger scroll scaled to 0.33", H.li.touches[0].y, 1533)
H.send(cat({E("ABS_MT_SLOT",0),E("ABS_MT_TRACKING_ID",-1),E("ABS_MT_SLOT",1),E("ABS_MT_TRACKING_ID",-1)}, K(0)))
-- 6. firmware-reported palm is still forwarded as MT_TOOL_PALM
H.send(cat({E("ABS_MT_SLOT",0),E("ABS_MT_TRACKING_ID",50),E("ABS_MT_POSITION_X",2000),E("ABS_MT_POSITION_Y",1500),E("ABS_MT_TOOL_TYPE",2)}, K(1)))
H.check("firmware palm forwarded with tool palm", H.li.touches[0] and H.li.touches[0].tool, 2)
H.send({E("ABS_MT_TOOL_TYPE",0)})
H.check("firmware palm turns finger", H.li.touches[0].tool, 0)
H.send(cat({E("ABS_MT_TRACKING_ID",-1)}, K(0)))
-- 7. slow pointer motion next to a hidden thumb is not held by plugin 30
H.send(cat({E("ABS_MT_SLOT",0),E("ABS_MT_TRACKING_ID",60),E("ABS_MT_POSITION_X",1000),E("ABS_MT_POSITION_Y",200)}, K(1)), 0)
H.send(cat({E("ABS_MT_SLOT",1),E("ABS_MT_TRACKING_ID",61),E("ABS_MT_POSITION_X",3000),E("ABS_MT_POSITION_Y",2000)}, K(2)), 10000)
local fwd, t = 0, 160000
for i=1,30 do t=t+25000; local fr = H.send({E("ABS_MT_POSITION_X",3000+i)}, t)
  for _,e in ipairs(fr) do if e.usage==evdev.ABS_MT_POSITION_X then fwd=fwd+1 end end end
H.check("slow motion beside hidden thumb forwarded (of 30)", fwd, 30)
print(H.ok and "ALL PASS" or "SOME FAILED")
